// Generates src/trackData.generated.js from real circuit centerlines.
// Source: bacinger/f1-circuits GeoJSON (MIT, see tools/data/LICENSE-f1-circuits.md).
//
// Pipeline: lon/lat -> local meters (x = east, z = south, matching three.js with
// north = -z) -> closed centripetal Catmull-Rom -> arc-length resample (4 m)
// -> light smoothing to remove digitising kinks.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(here, 'data/circuits.geojson'), 'utf8'));

const IDS = { monza: 'it-1922', suzuka: 'jp-1962', spa: 'be-1925' };
const STEP = 4; // output spacing in meters

function project(coords) {
  const lat0 = coords.reduce((a, c) => a + c[1], 0) / coords.length;
  const lon0 = coords.reduce((a, c) => a + c[0], 0) / coords.length;
  const kx = 111320 * Math.cos((lat0 * Math.PI) / 180);
  const ky = 110540;
  let pts = coords.map(([lon, lat]) => [(lon - lon0) * kx, -(lat - lat0) * ky]);
  // GeoJSON loops repeat the first point at the end; drop duplicates.
  const out = [];
  for (const p of pts) {
    const q = out[out.length - 1];
    if (!q || Math.hypot(p[0] - q[0], p[1] - q[1]) > 0.5) out.push(p);
  }
  const f = out[0], l = out[out.length - 1];
  if (Math.hypot(f[0] - l[0], f[1] - l[1]) < 0.5) out.pop();
  return out;
}

// Centripetal Catmull-Rom (alpha = 0.5) on a closed loop.
function catmullClosed(P, sub) {
  const n = P.length, out = [];
  const tj = (ti, a, b) => ti + Math.pow(Math.hypot(b[0] - a[0], b[1] - a[1]), 0.5) + 1e-6;
  for (let i = 0; i < n; i++) {
    const p0 = P[(i - 1 + n) % n], p1 = P[i], p2 = P[(i + 1) % n], p3 = P[(i + 2) % n];
    const t0 = 0, t1 = tj(t0, p0, p1), t2 = tj(t1, p1, p2), t3 = tj(t2, p2, p3);
    for (let s = 0; s < sub; s++) {
      const t = t1 + ((t2 - t1) * s) / sub;
      const lerp = (a, b, ta, tb) => [
        ((tb - t) / (tb - ta)) * a[0] + ((t - ta) / (tb - ta)) * b[0],
        ((tb - t) / (tb - ta)) * a[1] + ((t - ta) / (tb - ta)) * b[1],
      ];
      const A1 = lerp(p0, p1, t0, t1), A2 = lerp(p1, p2, t1, t2), A3 = lerp(p2, p3, t2, t3);
      const B1 = lerp(A1, A2, t0, t2), B2 = lerp(A2, A3, t1, t3);
      out.push(lerp(B1, B2, t1, t2));
    }
  }
  return out;
}

function resample(P, step) {
  const n = P.length;
  const cum = [0];
  for (let i = 1; i <= n; i++) {
    const a = P[i - 1], b = P[i % n];
    cum.push(cum[i - 1] + Math.hypot(b[0] - a[0], b[1] - a[1]));
  }
  const L = cum[n];
  const m = Math.round(L / step);
  const ds = L / m;
  const out = [];
  let j = 0;
  for (let k = 0; k < m; k++) {
    const s = k * ds;
    while (cum[j + 1] < s) j++;
    const t = (s - cum[j]) / (cum[j + 1] - cum[j] || 1);
    const a = P[j], b = P[(j + 1) % n];
    out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
  }
  return { pts: out, length: L };
}

function smooth(P, iters, w) {
  const n = P.length;
  let cur = P.map((p) => p.slice());
  for (let it = 0; it < iters; it++) {
    const nxt = cur.map((p, i) => {
      const a = cur[(i - 1 + n) % n], b = cur[(i + 1) % n];
      return [p[0] + w * ((a[0] + b[0]) / 2 - p[0]), p[1] + w * ((a[1] + b[1]) / 2 - p[1])];
    });
    cur = nxt;
  }
  return cur;
}

function minRadius(P, k = 3) {
  const n = P.length;
  let minR = Infinity, at = 0;
  for (let i = 0; i < n; i++) {
    const a = P[(i - k + n) % n], b = P[i], c = P[(i + k) % n];
    const ab = Math.hypot(b[0] - a[0], b[1] - a[1]);
    const bc = Math.hypot(c[0] - b[0], c[1] - b[1]);
    const ca = Math.hypot(a[0] - c[0], a[1] - c[1]);
    const cross = Math.abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]));
    const R = cross < 1e-9 ? Infinity : (ab * bc * ca) / (2 * cross);
    if (R < minR) { minR = R; at = i; }
  }
  return { minR, at };
}

let out = '// AUTO-GENERATED by tools/gen-tracks.mjs - do not edit.\n';
out += '// Circuit centerlines derived from bacinger/f1-circuits (MIT License, (c) Tomislav Bacinger).\n';
out += '// Flat array [x0, z0, x1, z1, ...] in meters, ~4 m spacing, race direction, index 0 = start line.\n';
out += 'export const TRACK_POINTS = {\n';
for (const [key, id] of Object.entries(IDS)) {
  const f = src.features.find((x) => x.properties.id === id);
  const raw = project(f.geometry.coordinates);
  const dense = catmullClosed(raw, 24);
  let { pts } = resample(dense, 1);
  pts = smooth(pts, 40, 0.5); // ~ removes sub-10 m wiggles from digitising
  const res = resample(pts, STEP);
  const mr = minRadius(res.pts);
  console.log(`${key.padEnd(7)} raw=${raw.length} pts out=${res.pts.length} length=${res.length.toFixed(0)} m (official ${f.properties.length}) minR=${mr.minR.toFixed(1)} m @${mr.at}`);
  out += `  ${key}: [${res.pts.map((p) => `${p[0].toFixed(1)},${p[1].toFixed(1)}`).join(',')}],\n`;
}
out += '};\n';
fs.writeFileSync(path.join(here, '../src/trackData.generated.js'), out);
console.log('wrote src/trackData.generated.js', (out.length / 1024).toFixed(1), 'KB');
